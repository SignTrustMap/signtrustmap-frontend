export interface ExtractedCandidateItem {
  id: string
  signCode: string
  signName: string
  category: 'P' | 'W' | 'R' | 'I' | 'S'
  confidence: number // 0.0 to 1.0 (e.g. 0.96)
  cropFrameSec: number // seconds in video when detected
  timestampStr: string // e.g. "02:15"
  lat: number
  lng: number
  trafficDirection: string // e.g. "Northbound (018°)"
  distanceMeters: number // e.g. 14.5
  reviewStatus: 'Approved' | 'Pending' | 'Rejected'
  reviewCount: number
  reviewerVoteRatio?: string // e.g. "3/3 Agree"
  cropImageUrl?: string
}

