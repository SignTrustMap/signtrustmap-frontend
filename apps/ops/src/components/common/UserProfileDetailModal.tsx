import { useState, useEffect } from 'react'
import { ModalPortal } from '@/components/common/ModalPortal'
import { CircleNotch, X, Copy, Check } from '@phosphor-icons/react'
import {
  userService,
  getCachedUserProfile,
  type BackendUserItem,
  type UserProfileSummary,
} from '@/api/services/user.service'

const SYSTEM_ROLES = [
  { code: 'ADMIN', label: 'Admin' },
  { code: 'STAFF', label: 'Staff' },
  { code: 'REVIEWER', label: 'Reviewer' },
  { code: 'SURVEYOR', label: 'Surveyor' },
  { code: 'DRIVER', label: 'Driver' },
] as const

function formatFullDateTime(dateStr?: string | null): string {
  if (!dateStr) return '—'
  const d = new Date(dateStr)
  if (isNaN(d.getTime())) return dateStr
  return d.toLocaleString('vi-VN', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  })
}

function getStatusMeta(status?: string, isEn = false) {
  switch (status?.toUpperCase()) {
    case 'ACTIVE':
      return {
        label: isEn ? 'Active' : 'Hoạt động',
        textColor: 'text-emerald-700 dark:text-emerald-400 font-medium',
      }
    case 'SUSPENDED':
      return {
        label: isEn ? 'Suspended' : 'Tạm khóa',
        textColor: 'text-amber-700 dark:text-amber-400 font-medium',
      }
    case 'BANNED':
      return {
        label: isEn ? 'Banned' : 'Đã cấm',
        textColor: 'text-red-700 dark:text-red-400 font-medium',
      }
    default:
      return {
        label: status || '—',
        textColor: 'text-gray-600 dark:text-gray-400',
      }
  }
}

function ProfileAvatar({
  url,
  name,
}: {
  url?: string | null
  name?: string | null
}) {
  const [imgError, setImgError] = useState(false)

  useEffect(() => {
    setImgError(false)
  }, [url])

  const words = (name || '').trim().split(/\s+/).filter(Boolean)
  const initials =
    words.length >= 2
      ? (words[0][0] + words[words.length - 1][0]).toUpperCase()
      : (words[0]?.[0] || 'U').toUpperCase()

  if (url && !imgError) {
    return (
      <img
        src={url}
        alt={name || ''}
        onError={() => setImgError(true)}
        className="w-10 h-10 rounded-full object-cover border border-gray-200 dark:border-white/10 shrink-0"
      />
    )
  }

  return (
    <div className="w-10 h-10 text-xs rounded-full bg-neutral-100 dark:bg-white/10 text-neutral-700 dark:text-neutral-300 font-semibold flex items-center justify-center shrink-0 border border-neutral-200/60 dark:border-white/10 select-none font-mono">
      {initials}
    </div>
  )
}

function getSummaryDisplayName(summary?: UserProfileSummary | BackendUserItem | null): string {
  if (!summary) return ''
  const rawName = (summary.fullName ?? summary.full_name ?? '').trim()
  // Ignore synthetic fallback names generated by older mapper code (e.g. "Reviewer #12345678")
  if (rawName && !/^(Reviewer|Surveyor|Staff)\s+#[0-9a-f-]{6,}/i.test(rawName)) {
    return rawName
  }
  return (summary.email || '').trim()
}

/**
 * Resolves a user's display name from inline summary, shared cache, or /admin|moderation/users/:id.
 */
export function useResolvedUserProfile(
  userId?: string | null,
  initialUser?: UserProfileSummary | null
): { profile: BackendUserItem | null; displayName: string | null } {
  const [fetched, setFetched] = useState<BackendUserItem | null>(() => getCachedUserProfile(userId) || null)

  useEffect(() => {
    if (!userId) {
      setFetched(null)
      return
    }
    const cached = getCachedUserProfile(userId)
    if (cached) {
      setFetched(cached)
      return
    }
    // If initialUser already provides a real name, keep it immediately and still allow click to load full modal
    let active = true
    userService
      .getUserProfileById(userId)
      .then((res) => {
        if (active) setFetched(res)
      })
      .catch(() => {
        // Silently fall back to UUID display when user lookup fails
      })
    return () => {
      active = false
    }
  }, [userId])

  const name = getSummaryDisplayName(fetched) || getSummaryDisplayName(initialUser) || null
  return { profile: fetched, displayName: name }
}

export interface UserIdentityButtonProps {
  userId?: string | null
  initialUser?: UserProfileSummary | null
  prefix?: string
  isEn?: boolean
  onOpenProfile: (userId: string, initialUser?: UserProfileSummary | null) => void
  className?: string
}

/**
 * Displays user name first (falling back to UUID when unavailable) and opens UserProfileDetailModal on click.
 */
export function UserIdentityButton({
  userId,
  initialUser,
  prefix,
  isEn = false,
  onOpenProfile,
  className = '',
}: UserIdentityButtonProps) {
  const { profile, displayName } = useResolvedUserProfile(userId, initialUser)

  if (!userId) return null

  const identityText = displayName || `#${userId}`

  return (
    <button
      type="button"
      onClick={(e) => {
        e.stopPropagation()
        onOpenProfile(userId, profile || initialUser)
      }}
      className={`group/identity inline-flex items-baseline gap-1 min-w-0 max-w-full text-left cursor-pointer ${className}`}
      title={
        isEn
          ? `UUID: ${userId} — Click to view user details`
          : `UUID: ${userId} — Bấm để xem thông tin người dùng`
      }
    >
      {prefix && (
        <span className="shrink-0 text-gray-500 dark:text-gray-400">
          {prefix}:
        </span>
      )}
      <span
        className={`truncate min-w-0 group-hover/identity:text-[#007b8b] dark:group-hover/identity:text-[#00c4de] group-hover/identity:underline transition-colors ${
          prefix ? 'text-gray-700 dark:text-gray-200' : ''
        }`}
      >
        {identityText}
      </span>
    </button>
  )
}

export interface UserProfileDetailModalProps {
  userId: string | null
  initialSummary?: UserProfileSummary | null
  isEn?: boolean
  onClose: () => void
}

/**
 * Read-only User Profile modal matching UsersPage detail modal styling.
 */
export function UserProfileDetailModal({
  userId,
  initialSummary,
  isEn = false,
  onClose,
}: UserProfileDetailModalProps) {
  const [profile, setProfile] = useState<BackendUserItem | null>(() =>
    userId ? getCachedUserProfile(userId) || null : null
  )
  const [isLoading, setIsLoading] = useState(false)
  const [loadError, setLoadError] = useState(false)
  const [copiedId, setCopiedId] = useState(false)

  useEffect(() => {
    if (!userId) {
      setProfile(null)
      setIsLoading(false)
      setLoadError(false)
      setCopiedId(false)
      return
    }

    const cached = getCachedUserProfile(userId)
    if (cached) {
      setProfile(cached)
      setIsLoading(false)
      setLoadError(false)
      return
    }

    let active = true
    setIsLoading(true)
    setLoadError(false)

    userService
      .getUserProfileById(userId)
      .then((res) => {
        if (!active) return
        setProfile(res)
      })
      .catch(() => {
        if (active) setLoadError(true)
      })
      .finally(() => {
        if (active) setIsLoading(false)
      })

    return () => {
      active = false
    }
  }, [userId])

  useEffect(() => {
    if (!userId) return
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose()
    }
    window.addEventListener('keydown', handleKeyDown)
    return () => window.removeEventListener('keydown', handleKeyDown)
  }, [userId, onClose])

  if (!userId) return null

  const fullName =
    getSummaryDisplayName(profile) ||
    getSummaryDisplayName(initialSummary) ||
    (isEn ? 'Unnamed user' : 'Chưa đặt tên')
  const email = profile?.email || initialSummary?.email || '—'
  const avatarUrl =
    profile?.avatar_url ??
    profile?.avatarUrl ??
    initialSummary?.avatarUrl ??
    initialSummary?.avatar_url ??
    null
  const roles = (profile?.roles || []).map((r) => r.toUpperCase())
  const status = profile?.status
  const statusMeta = getStatusMeta(status, isEn)

  return (
    <ModalPortal>
      <div
        role="dialog"
        aria-modal="true"
        className="fixed inset-0 z-[120] bg-black/60 backdrop-blur-xs flex items-center justify-center p-3 sm:p-5 overflow-y-auto animate-in fade-in duration-200"
        onClick={onClose}
      >
        <div
          onClick={(e) => e.stopPropagation()}
          className="bg-white dark:bg-[#0A171C] border border-gray-200 dark:border-white/15 rounded-2xl max-w-[560px] w-full shadow-2xl animate-in zoom-in-95 my-auto max-h-[92vh] flex flex-col overflow-hidden text-xs text-gray-800 dark:text-gray-200"
        >
          {/* Modal Header */}
          <div className="flex items-center justify-between px-5 py-3.5 border-b border-gray-200 dark:border-white/10 bg-gray-50/60 dark:bg-white/[0.02] shrink-0">
            <div className="flex items-center gap-2 min-w-0">
              <span className="font-bold text-sm text-gray-900 dark:text-white truncate">
                {getSummaryDisplayName(profile) || getSummaryDisplayName(initialSummary) || `#${userId.slice(0, 8)}`}
              </span>
              {status && (
                <>
                  <span className="text-gray-300 dark:text-gray-600">•</span>
                  <span className={`text-xs whitespace-nowrap ${statusMeta.textColor}`}>
                    {statusMeta.label}
                  </span>
                </>
              )}
            </div>

            <button
              type="button"
              onClick={onClose}
              className="w-8 h-8 rounded-lg flex items-center justify-center text-gray-400 hover:text-gray-700 dark:hover:text-white hover:bg-gray-100 dark:hover:bg-white/10 transition-colors cursor-pointer shrink-0 ml-2"
              title={isEn ? 'Close (Esc)' : 'Đóng (Esc)'}
            >
              <X size={18} weight="bold" />
            </button>
          </div>

          {/* Modal Body */}
          <div className="p-5 space-y-4 overflow-y-auto text-xs">
            {/* 1. Profile Card */}
            <div className="flex items-center gap-3.5 p-3.5 rounded-xl border border-gray-200/80 dark:border-white/10 bg-gray-50/50 dark:bg-white/[0.02]">
              <ProfileAvatar url={avatarUrl} name={fullName} />
              <div className="min-w-0 flex-1">
                <h4 className="text-sm font-bold text-gray-900 dark:text-white truncate">
                  {fullName}
                </h4>
                <p className="text-xs text-gray-500 dark:text-gray-400 font-mono truncate">
                  {email}
                </p>
              </div>
              {isLoading && (
                <CircleNotch size={16} className="animate-spin text-[#007b8b] dark:text-[#00c4de] shrink-0" />
              )}
            </div>

            {/* 2. Key-Value Info Card */}
            <div className="rounded-xl border border-gray-200/80 dark:border-white/10 bg-gray-50/50 dark:bg-white/[0.02] divide-y divide-gray-200/60 dark:divide-white/5">
              <div className="flex items-center justify-between gap-3 py-2 px-3.5">
                <span className="text-gray-500 dark:text-gray-400 shrink-0">
                  {isEn ? 'User ID' : 'Mã người dùng'}
                </span>
                <div className="flex items-center gap-1.5 font-mono text-gray-800 dark:text-gray-200 min-w-0">
                  <span className="select-all break-all text-right">{userId}</span>
                  <button
                    type="button"
                    onClick={() => {
                      navigator.clipboard.writeText(userId)
                      setCopiedId(true)
                      setTimeout(() => setCopiedId(false), 2000)
                    }}
                    className="text-gray-400 hover:text-gray-700 dark:hover:text-white cursor-pointer shrink-0"
                    title={isEn ? 'Copy UUID' : 'Sao chép UUID'}
                  >
                    {copiedId ? <Check size={12} className="text-emerald-500" /> : <Copy size={12} />}
                  </button>
                </div>
              </div>

              <div className="flex items-center justify-between py-2 px-3.5">
                <span className="text-gray-500 dark:text-gray-400">
                  {isEn ? 'Phone' : 'Số điện thoại'}
                </span>
                <span className="font-mono text-gray-800 dark:text-gray-200">
                  {profile?.phone || '—'}
                </span>
              </div>

              <div className="flex items-center justify-between py-2 px-3.5">
                <span className="text-gray-500 dark:text-gray-400">
                  {isEn ? 'Created at' : 'Ngày tạo'}
                </span>
                <span className="font-mono text-gray-800 dark:text-gray-200">
                  {formatFullDateTime(profile?.created_at || profile?.createdAt)}
                </span>
              </div>

              {(profile?.updated_at || profile?.updatedAt) && (
                <div className="flex items-center justify-between py-2 px-3.5">
                  <span className="text-gray-500 dark:text-gray-400">
                    {isEn ? 'Last updated' : 'Cập nhật lần cuối'}
                  </span>
                  <span className="font-mono text-gray-800 dark:text-gray-200">
                    {formatFullDateTime(profile.updated_at || profile.updatedAt)}
                  </span>
                </div>
              )}
            </div>

            {loadError && !profile ? (
              <p className="text-[11px] text-amber-600 dark:text-amber-400">
                {isEn
                  ? 'Unable to load extended profile details from server.'
                  : 'Không thể tải thêm thông tin chi tiết người dùng từ máy chủ.'}
              </p>
            ) : (
              <>
                {/* 3. Vai trò */}
                <div className="space-y-1.5">
                  <label className="block text-xs font-bold text-gray-900 dark:text-white">
                    {isEn ? 'Roles' : 'Vai trò'}
                  </label>
                  <div className="grid grid-cols-2 sm:grid-cols-5 gap-1.5">
                    {SYSTEM_ROLES.map((r) => {
                      const isAssigned = roles.includes(r.code)
                      return (
                        <div
                          key={r.code}
                          className={`py-2 px-2 rounded-lg border text-xs font-semibold text-center select-none ${
                            isAssigned
                              ? 'bg-[#007b8b] text-white border-[#007b8b] dark:bg-[#00c4de] dark:text-black dark:border-[#00c4de] shadow-xs'
                              : 'bg-white/60 dark:bg-black/20 border-gray-200 dark:border-white/10 text-gray-400 dark:text-gray-500'
                          }`}
                        >
                          {r.label}
                        </div>
                      )
                    })}
                  </div>
                </div>

                {/* 4. Trạng thái */}
                <div className="space-y-1.5">
                  <label className="block text-xs font-bold text-gray-900 dark:text-white">
                    {isEn ? 'Status' : 'Trạng thái'}
                  </label>
                  <div className="grid grid-cols-3 gap-1.5">
                    <div
                      className={`py-2 px-2 rounded-lg border text-xs font-semibold text-center select-none ${
                        status === 'ACTIVE'
                          ? 'bg-emerald-600 text-white border-emerald-600 shadow-xs'
                          : 'bg-white/60 dark:bg-black/20 border-gray-200 dark:border-white/10 text-gray-400 dark:text-gray-500'
                      }`}
                    >
                      {isEn ? 'Active' : 'Hoạt động'}
                    </div>
                    <div
                      className={`py-2 px-2 rounded-lg border text-xs font-semibold text-center select-none ${
                        status === 'SUSPENDED'
                          ? 'bg-amber-600 text-white border-amber-600 shadow-xs'
                          : 'bg-white/60 dark:bg-black/20 border-gray-200 dark:border-white/10 text-gray-400 dark:text-gray-500'
                      }`}
                    >
                      {isEn ? 'Suspended' : 'Tạm khóa'}
                    </div>
                    <div
                      className={`py-2 px-2 rounded-lg border text-xs font-semibold text-center select-none ${
                        status === 'BANNED'
                          ? 'bg-red-600 text-white border-red-600 shadow-xs'
                          : 'bg-white/60 dark:bg-black/20 border-gray-200 dark:border-white/10 text-gray-400 dark:text-gray-500'
                      }`}
                    >
                      {isEn ? 'Banned' : 'Đã cấm'}
                    </div>
                  </div>
                </div>
              </>
            )}
          </div>

          {/* Modal Footer */}
          <div className="flex items-center justify-end px-5 py-3 border-t border-gray-200 dark:border-white/10 bg-gray-50/60 dark:bg-white/[0.02] shrink-0">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2 rounded-xl border border-gray-200 dark:border-white/15 text-gray-700 dark:text-gray-300 hover:bg-gray-100 dark:hover:bg-white/5 font-semibold transition-colors cursor-pointer"
            >
              {isEn ? 'Close' : 'Đóng'}
            </button>
          </div>
        </div>
      </div>
    </ModalPortal>
  )
}

